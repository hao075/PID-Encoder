int main(void)
{
  HAL_Init();
  SystemClock_Config();

  MX_GPIO_Init();
  MX_I2C1_Init();
  MX_TIM1_Init();
  MX_TIM2_Init();
  MX_USART1_UART_Init();
  MX_TIM3_Init();

  /* USER CODE BEGIN 2 */
  // Kh?i t?o module PID Motor
  PID_Motor_Init(&htim1, &htim2);
  
  // Kh?i d?ng ng?t UART nh?n d? li?u
  HAL_UART_Receive_IT(&huart1, &rxData, 1);       

  HAL_Delay(100);
  
  // Kh?i d?ng ng?t Timer 3 co s? (1kHz / 1ms)
  HAL_TIM_Base_Start_IT(&htim3);
  /* USER CODE END 2 */

  uint32_t lastDisplayTick = 0;
  
  while (1)
  {
    // Tác v? n?n: G?i d? li?u qua UART lên PC m?i 200ms
    if (HAL_GetTick() - lastDisplayTick >= 200)
    {
      lastDisplayTick = HAL_GetTick();

      char uartBuf[64];
      int len = sprintf(uartBuf, "SP:%.1f,PV:%.1f\r\n", (double)speedSetpoint, (double)filteredSpeed);
      
      if (huart1.gState == HAL_UART_STATE_READY) {
        HAL_UART_Transmit(&huart1, (uint8_t*)uartBuf, len, 20);
      }
    }
  }
}

